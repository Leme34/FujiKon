/**
 * 「16 张作品 · 通透胶片」——由 tools/color-audit-v16（见仓库 tools 目录）中的
 * fit16.py / fingerprint16.py / semantic.py 从用户提供的 16 张目标成片拟合。
 *
 * 数据来源与拟合口径：
 *  - Ground truth 为用户亲自挑选、风格一致的 16 张成片，覆盖 4 类场景：
 *    夏日青蓝（蓝天/青绿裙/蓝绣球）、秋冬暖橙（橙枫/落叶/木栏）、
 *    逆光近景人像、暖橙特写。
 *  - 关键辨识（fingerprint16.py + semantic.py）：只有「跨 4 批次冷暖场景都稳定」
 *    的量才是滤镜特征。实测全局 mean_a 从 -2.0（夏日青蓝）波动到 +7.4（暖橙），
 *    即全局色偏几乎全是「场景色」，不能学进滤镜；而肤色 hue 26.6~29.9°、
 *    暖橙高光 hue 31.4~32.0°（±0.3°）、绿 109.8~127.3°、青蓝 197.2~215.4°
 *    跨批次稳定，说明滤镜「不扭曲色相」。因此色彩层严格保持恒等：
 *    saturation=0 / hue=0 / colorBlender 全 0 / colorGrading 全 0。
 *  - 唯一跨场景稳定的可泛化特征是影调：目标 L 分位
 *    p01≈5 / p50≈58 / p95≈94 / p99≈97、死黑 0、死白≈0.4%、L_std≈24，
 *    即「抬黑位、提亮中间调、压高光、中低对比、明亮通透」的胶片负片曲线。
 *  - 拟合方法：对 13 张多样化中性源图与 16 张成片各取聚合亮度 CDF，做
 *    CDF 反演得单调 tone LUT，向恒等收缩 alpha=0.85 并 savgol 平滑。
 *    close_loop.py 验证套用后 p50=54.3（目标 58）、p95=93.4（目标 94），
 *    灰阶探针证明 LUT 完全不引入 a/b 色偏。
 *
 * 与 1.6.32 那版「凭官方 brief 往里加青/加色彩层」的根本区别：
 * 那版把场景色误当滤镜色，导致套用后泛青发脏，用户判定「效果很差」并回退。
 * 本预设只做影调、不染色，可泛化到任意场景而不会出现偏色事故。
 *
 * 诚实边界：目标只有成片（after），没有 before/after 配对，也没有机内真实
 * gamma/LUT。因此这是「统计风格拟合」，不是像素级 ΔE00 复刻；作品里的逆光
 * 光感、暖橙主体、胶片颗粒来自拍摄与场景，无法由滤镜凭空生成。
 *
 * 与官方条目 [PENG_MANGO_VITALITY_FILM] 及社区近似条目相互独立：
 * contentHash 不同、参数不同，不覆盖、不替换任何现有条目。
 */
