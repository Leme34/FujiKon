    fun toPreset(): Preset {
        val control = PictureControl(
            format = PictureControlFormat.NP3,
            version = "1.0",
            name = NAME,
            baseProfile = BaseProfiles.FLEXIBLE_COLOR,
            baseProfileName = "Flexible Color",
            curve = CURVE,
            // 影调已全部写进拟合 LUT；色彩层恒等（不引入任何色偏）。
